import assert from 'node:assert/strict';
import {VECTOR_TILE_URL,tilesForAnchor,parseVectorBuildings,loadVectorBuildings} from './earth-vector-buildings.mjs';
assert.ok(VECTOR_TILE_URL.startsWith('/api/osm/tiles/'), 'building tiles must first load from the same-origin proxy');
const enc=n=>{let v=Math.floor(n),out=[];do{let b=v&127;v=Math.floor(v/128);if(v)b|=128;out.push(b)}while(v);return out};
const field=(n,wire,v)=>[...enc(n*8+wire),...(wire===2?[...enc(v.length),...v]:enc(v))];
const utf=s=>[...new TextEncoder().encode(s)];
const zig=n=>n<0?-2*n-1:2*n;
const anchor={lat:51.508,lon:-0.126};const tiles=tilesForAnchor(anchor);assert.ok(tiles.length>0&&tiles.length<=16);
const first=tiles[0];const z=first.z,n=2**z;
const sin=Math.sin(anchor.lat*Math.PI/180),tx=(anchor.lon+180)/360*n,ty=(1-Math.log((1+sin)/(1-sin))/(2*Math.PI))/2*n;
const tile={...first,x:Math.floor(tx),y:Math.floor(ty)};
const cx=Math.round((tx-tile.x)*4096),cy=Math.round((ty-tile.y)*4096);
const corners=[[cx-40,cy-30],[cx+40,cy-30],[cx+40,cy+30],[cx-40,cy+30]];
let x=0,y=0;const geom=[9];for(const [a,b] of corners){geom.push(...enc(zig(a-x)),...enc(zig(b-y)));x=a;y=b; if(a===corners[0][0]&&b===corners[0][1])geom.push(26)}geom.push(15);
const feature=[...field(1,0,17),...field(2,2,[0,0]),...field(3,0,3),...field(4,2,geom)];
const layer=[...field(1,2,utf('building')),...field(2,2,feature),...field(3,2,utf('render_height')),...field(4,2,field(4,0,18)),...field(5,0,4096),...field(15,0,2)];
const bytes=new Uint8Array(field(3,2,layer));
const buildings=parseVectorBuildings(bytes,anchor,tile);
assert.equal(buildings.length,1,'A mapped polygon must decode as an actual footprint');
assert.equal(buildings[0].heightMetres,null,'Tile heights must not be labelled measured');
assert.equal(buildings[0].estimatedHeightMetres,18);
assert.ok(buildings[0].outline.length>=4);
assert.ok(buildings[0].id.startsWith('tile/'));
const result=await loadVectorBuildings(anchor,{fetchImpl:async()=>({ok:true,headers:{get:()=>String(bytes.length)},arrayBuffer:async()=>bytes.buffer})});
assert.ok(result.buildings.length>=1,'A vector-tile area must load actual mapped buildings');
assert.equal(result.sourceType,'vector-tile');
console.log('PASS — OpenFreeMap vector-tile real building polygons, estimated-height provenance, public-tile fallback');
